// "Cast voices": one place to choose the voice of every character (and the narrator) for ALL scenes.
// project.cast = { narrator: Cfg, [characterId]: Cfg }
// Cfg = { engine: 'keep' | 'browser' | 'gemini', gVoice, style, bVoice, rate, pitch }

import * as gem from './gemini.js';
import * as tts from './tts.js';
import { relayoutScene, dialogSig } from './retime.js';
import { dialogDuration, estimateTtsDuration } from '../engine/renderer.js';
import { saveLocal } from '../state.js';

export const defaultCfg = () => ({ engine: 'keep', gVoice: 'Kore', style: '', bVoice: '', rate: null, pitch: null });   // empty / null = keep what each line already has
export const ensureCast = (project) => (project.cast ||= {});
export const cfgFor = (project, key) => ({ ...defaultCfg(), ...(ensureCast(project)[key] || {}) });
export const isNarration = (d) => !!d.narrator || (!!d.silent && d.bubble === false);
export function castKey(scene, d) { if (isNarration(d)) return 'narrator'; const a = scene.actors[d.actor]; return a ? a.characterId : null; }

/** [{ key, name, lines }] – narrator first, then every character of the project. */
export function castRows(project) {
  const count = new Map();
  for (const s of project.scenes) for (const d of s.dialogs) { if (!String(d.text || '').trim()) continue; const k = castKey(s, d); if (k) count.set(k, (count.get(k) || 0) + 1); }
  const rows = [{ key: 'narrator', name: '🎙 Narrator (voice-over lines)', lines: count.get('narrator') || 0 }];
  for (const c of project.characters) rows.push({ key: c.id, name: c.name, lines: count.get(c.id) || 0 });
  return rows;
}

function dropClip(app, d) { if (d.audioId && d.gen) app.store.remove(d.audioId); }

/** Which lines would be (re)generated by Gemini with the current cast settings. */
export function planGemini(project, store, model) {
  const todo = [], done = [];
  project.scenes.forEach((s, si) => s.dialogs.forEach((d, di) => {
    if (!String(d.text || '').trim()) return;
    const key = castKey(s, d); if (!key) return;
    const cfg = cfgFor(project, key); if (cfg.engine !== 'gemini') return;
    if (d.audioId && !d.gen) return;                 // your own recording / upload: never touched
    const sig = gem.geminiSig(model, cfg.gVoice, cfg.style, d.text);
    if (d.gen && d.gen.sig === sig && store.has(d.audioId)) done.push(d); else todo.push({ si, di, s, d, cfg, sig });
  }));
  return { todo, done };
}

/** Apply the cast to every dialog of every scene, generate missing Gemini audio, then re-time the scenes. */
export async function applyCast(app, { pauseMs = 3000, onStatus, signal } = {}) {
  const p = app.project, model = gem.getModel(), apiKey = gem.getKey();
  const touched = new Set(); let changedBrowser = 0;
  // 1) browser voices / reverting from Gemini
  p.scenes.forEach((s, si) => s.dialogs.forEach((d) => {
    const key = castKey(s, d); if (!key) return;
    const cfg = cfgFor(p, key);
    if (cfg.engine === 'browser') {
      if (d.audioId && !d.gen) return;
      if (d.gen) { dropClip(app, d); d.audioId = null; delete d.gen; d.source = 'tts'; d.duration = estimateTtsDuration(d.text, cfg.rate || d.rate || 1); touched.add(si); }
      if (d.source === 'tts') { if (cfg.bVoice) d.voice = cfg.bVoice; if (cfg.rate) d.rate = cfg.rate; if (cfg.pitch) d.pitch = cfg.pitch; changedBrowser++; }
    }
  }));
  // 2) Gemini generation
  const { todo } = planGemini(p, app.store, model);
  if (todo.length && !apiKey) throw new Error('Paste your Gemini API key first (Cast voices → API key).');
  let n = 0, failed = [];
  for (const t of todo) {
    if (signal?.aborted) break;
    n++;
    onStatus?.({ phase: 'gen', i: n, total: todo.length, text: t.d.text, voice: t.cfg.gVoice });
    try {
      const r = await gem.generateSpeech({ text: t.d.text, voice: t.cfg.gVoice, style: t.cfg.style, model, apiKey, signal },
        { onWait: (ms, e) => onStatus?.({ phase: 'wait', ms, error: e.message, i: n, total: todo.length }) });
      const samples = gem.trimSilence(r.samples, r.sampleRate);
      const blob = gem.pcmToWavBlob(samples, r.sampleRate);
      const clip = await app.store.add(blob, `gemini-${t.cfg.gVoice}-s${t.si + 1}-l${t.di + 1}.wav`);
      dropClip(app, t.d);
      t.d.audioId = clip.id; t.d.source = 'upload'; t.d.trimStart = 0; t.d.trimEnd = 0; t.d.lead = 0; t.d.duration = clip.duration;
      t.d.gen = { provider: 'gemini', model, voice: t.cfg.gVoice, style: t.cfg.style, sig: t.sig };
      touched.add(t.si);
      saveLocal(p);                                   // checkpoint: nothing is lost if the tab closes
    } catch (e) {
      if (e.name === 'AbortError') break;
      failed.push({ n, text: t.d.text, error: e.message });
      if (e.status === 401 || e.status === 403 || e.status === 400 || e.status === 404) { failed.fatal = e.message; break; }
    }
    if (pauseMs && n < todo.length) await new Promise((r) => setTimeout(r, pauseMs));
  }
  // 3) re-time every scene that got new audio so nothing is cut and lip-sync matches
  const info = app.store.info; let retimed = 0;
  for (const si of touched) {
    const s = p.scenes[si]; const map = new Map();
    for (const d of s.dialogs) {
      if (d.audioId && app.store.has(d.audioId)) map.set(d.id, { duration: Math.max(0.3, dialogDuration(d, info) - 0.1), lead: 0 });
      else map.set(d.id, { duration: Math.max(0.3, (d.duration || 2) - 0.1), lead: d.lead || 0 });
    }
    relayoutScene(s, map, { gap: 0.4, minTail: 0.6, pad: 0.1, firstPad: 0.15, syncExtra: p.ttsSync || 0 }); retimed++;
  }
  app.commit('cast voices');
  return { generated: todo.length - failed.length, failed, retimed, changedBrowser, total: todo.length };
}

/** Speak a short sample with the settings of one cast row. */
export async function previewCfg(app, cfg, text) {
  if (cfg.engine === 'browser') { tts.cancel(); await tts.speak(text, { voice: cfg.bVoice, rate: cfg.rate || 1, pitch: cfg.pitch || 1 }); return; }
  if (cfg.engine !== 'gemini') throw new Error('Choose Browser voice or Gemini first.');
  const r = await gem.generateSpeech({ text, voice: cfg.gVoice, style: cfg.style, model: gem.getModel(), apiKey: gem.getKey() }, { retries: 2 });
  const ctx = app.store.ctx; await app.store.resume();
  const f = new Float32Array(r.samples.length); for (let i = 0; i < f.length; i++) f[i] = r.samples[i] / 32768;
  const buf = ctx.createBuffer(1, f.length, r.sampleRate); buf.copyToChannel(f, 0);
  const src = ctx.createBufferSource(); src.buffer = buf; src.connect(ctx.destination); src.start();
  await new Promise((res) => { src.onended = res; });
}
